    /** 取某资源的内容库（未收录返回 null，回退通用模板） */
    public static LessonStep[] of(String resourceCode) {
        return LIBRARY.get(resourceCode);
    }

    /** 取某资源第 stepNumber 步：优先内容库，回退 StepTemplateFactory 通用模板 */
    public static LessonStep lesson(String resourceCode, int stepNumber, String resourceTitle) {
        LessonStep[] lessons = of(resourceCode);
        if (lessons != null && stepNumber >= 1 && stepNumber <= lessons.length) {
            return lessons[stepNumber - 1];
        }
        StepTemplateFactory.StepTemplate t = StepTemplateFactory.templateOf(stepNumber);
        if (t == null) {
            return new LessonStep("步骤 " + stepNumber, "");
        }
        return new LessonStep(t.title(), t.render(resourceTitle));
    }

    private static LessonStep step(String title, String content) {
        return new LessonStep(title, content);
    }

    private static LessonStep[] lessons(LessonStep... steps) {
        return steps;
    }
